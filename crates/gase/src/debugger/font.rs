/// The glyph for `c`; characters outside printable ASCII show as `?`.
#[must_use]
pub fn glyph(c: char) -> &'static [u8; 8] {
    let index = match u8::try_from(c) {
        Ok(byte @ FIRST..=0x7F) => byte - FIRST,
        _ => b'?' - FIRST,
    };
    &GLYPHS[usize::from(index)]
}

/// Draw `text` with its top-left corner at (`x`, `y`) in `color`; the
/// background is left as it is. Returns the x coordinate after the text.
pub fn draw_text(canvas: &mut Canvas, x: usize, y: usize, text: &str, color: u32) -> usize {
    let mut cx = x;
    for c in text.chars() {
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..GLYPH_SIZE {
                if bits >> col & 1 != 0 {
                    canvas.set(cx + col, y + row, color);
                }
            }
        }
        cx += GLYPH_SIZE;
    }
    cx
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_lookup() {
        assert_eq!(
            glyph('A'),
            &[0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]
        );
        assert_eq!(glyph(' '), &[0; 8]);
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(glyph('\n'), glyph('?'));
    }

    #[test]
    fn text_renders_into_the_pixel_buffer() {
        let mut canvas = Canvas::new(24, 8, 0);
        let end = draw_text(&mut canvas, 8, 0, "1", 0xFFFFFF);
        assert_eq!(end, 16);
        // '1' row 0 = 0x0C: pixels 2 and 3 of the cell are set.
        let row0: Vec<bool> = (8..16).map(|x| canvas.get(x, 0) != 0).collect();
        assert_eq!(row0, [false, false, true, true, false, false, false, false]);
        // Row 6 = 0x3F: pixels 0-5.
        let row6: Vec<bool> = (8..16).map(|x| canvas.get(x, 6) != 0).collect();
        assert_eq!(row6, [true, true, true, true, true, true, false, false]);
        // Nothing drawn outside the cell, and the colour is the one asked for.
        assert!((0..8).all(|x| (0..8).all(|y| canvas.get(x, y) == 0)));
        assert_eq!(canvas.get(10, 0), 0xFFFFFF);
        // Count every lit pixel of the glyph.
        let lit = canvas.pixels.iter().filter(|&&p| p != 0).count();
        let expected: u32 = glyph('1').iter().map(|b| b.count_ones()).sum();
        assert_eq!(lit, expected as usize);
    }

    #[test]
    fn text_is_clipped_at_the_edge() {
        let mut canvas = Canvas::new(10, 4, 0);
        draw_text(&mut canvas, 4, 0, "##", 1); // would overflow both ways
        assert_eq!(canvas.pixels.len(), 40);
    }
}
